import type { ImageAssetAuthority } from "./asset-authority.js";
import type { ArtifactRef, JsonValue } from "../contracts.js";
import type { ImagegenActivationController } from "./activation.js";
import type {
  ImagegenExportReceiptV1,
  ImagegenExportRequestV1,
  ImagegenNodeInputPolicyV1,
  ImagegenProfileSnapshotV1,
  ImagegenProfileV1,
  ImagegenStorageCommitReceiptV1,
  ImagegenStorageReleaseReceiptV1,
  ImagegenStorageReservationReceiptV1,
} from "../skill-contracts/imagegen.js";

export interface ImagegenNodeClassSafetyPolicyV1 {
  readonly schema_version: 1;
  readonly class_type: string;
  /**
   * `backend_output` is reserved for the profile's single declared output node. It permits the
   * backend to expose generated bytes through its registered output API, but grants no caller-
   * selected path, URL, download, subprocess, or arbitrary filesystem authority.
   */
  readonly execution_class: "pure_compute" | "backend_output" | "registered_input";
  readonly inputs: readonly ImagegenNodeInputPolicyV1[];
}

export interface ResolvedImagegenProfileV1 {
  readonly profile: ImagegenProfileV1;
  readonly snapshot: ImagegenProfileSnapshotV1;
  readonly backend_key_sha256: string;
}

export interface ImagegenProfileRegistry {
  resolve(profileId?: string): ResolvedImagegenProfileV1;
}

export interface ImagegenExportDestinationV1 {
  readonly destination_id: string;
  readonly max_files: number;
  readonly max_bytes: number;
}

export interface ImagegenExportFileV1 {
  readonly filename: string;
  readonly source_ref: ArtifactRef;
}

export interface ImagegenExportRegistry {
  resolve(intent: ImagegenExportRequestV1): ImagegenExportDestinationV1;
  export(input: {
    readonly intent: ImagegenExportRequestV1;
    readonly files: readonly ImagegenExportFileV1[];
    readonly selected_filename: string;
    readonly readArtifact: (ref: ArtifactRef) => Uint8Array;
  }): ImagegenExportReceiptV1;
}

export interface ImagegenStorageReservationInputV1 {
  readonly run_id: string;
  readonly admission_sha256: string;
  readonly requested_bytes: number;
  readonly requested_seed: number | null;
}

export interface ImagegenStorageAdmission {
  reserve(input: ImagegenStorageReservationInputV1): ImagegenStorageReservationReceiptV1;
  commit(input: {
    readonly reservation_id: string;
    readonly commit_key: string;
    readonly byte_length: number;
  }): ImagegenStorageCommitReceiptV1;
  release(reservationId: string): ImagegenStorageReleaseReceiptV1;
  reservation(reservationId: string): ImagegenStorageReservationReceiptV1 | undefined;
}

export interface ImagegenStartAdmissionProvidersV1 {
  readonly assets?: ImageAssetAuthority;
  readonly profiles: ImagegenProfileRegistry;
  readonly exports: ImagegenExportRegistry;
  readonly storage: ImagegenStorageAdmission;
  /** Closed disabled/canary/enabled activation authority; absence must never admit a start. */
  readonly activation: ImagegenActivationController;
}

export interface ImagegenOperationPreparationV1 {
  readonly request_ref: ArtifactRef;
  readonly submitted_graph_ref: ArtifactRef;
  readonly submitted_graph: Readonly<Record<string, JsonValue>>;
}
